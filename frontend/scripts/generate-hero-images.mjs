// Builds everything the page derives from the hero photo, public/images/hero.png:
// responsive WebP variants (so the main visual never waits for on-demand image
// optimisation), a tiny inline preview, and a JPEG for link previews.
// Runs before `dev` and `build`. Skips the work only when the photo and this
// script are byte-for-byte the ones the outputs were made from: a content
// fingerprint rather than file times, so a replaced photo is always picked up,
// whatever its timestamp. Use --force to rebuild anyway.
import { createHash } from 'node:crypto';
import { mkdir, readdir, readFile, rm, writeFile } from 'node:fs/promises';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import sharp from 'sharp';

const SCRIPT = fileURLToPath(import.meta.url);
const root = join(dirname(SCRIPT), '..');
const SOURCE = join(root, 'public/images/hero.png');
const OUT_DIR = join(root, 'src/assets/hero');
const MODULE = join(OUT_DIR, 'hero-image.ts');
// Capped at the photo's own width, so the widest variant is the photo at full resolution.
const WIDTHS = [640, 960, 1200, 1448, 1920];
const QUALITY = 82;
const PREVIEW_WIDTH = 40;
const OG_FILE = 'hero-og.jpg';
const OG_WIDTH = 1200;

const [photo, script] = await Promise.all([readFile(SOURCE), readFile(SCRIPT)]);
const fingerprint = createHash('sha256').update(photo).update(script).digest('hex').slice(0, 16);
const { width: sourceWidth, height: sourceHeight } = await sharp(photo).metadata();
const widths = [...new Set(WIDTHS.map((w) => Math.min(w, sourceWidth)))];
const outputs = [...widths.map((w) => `hero-${w}.webp`), OG_FILE];

await mkdir(OUT_DIR, { recursive: true });
const existing = await readdir(OUT_DIR);
const generated = await readFile(MODULE, 'utf8').catch(() => '');
const upToDate =
  generated.includes(`// fingerprint: ${fingerprint}\n`) && outputs.every((file) => existing.includes(file));
if (upToDate && !process.argv.includes('--force')) {
  console.log('[hero] images are up to date');
  process.exit(0);
}

// Remove variants left over from a previous photo of a different width.
for (const file of existing) {
  if (/^hero-.+\.(webp|jpg)$/.test(file) && !outputs.includes(file)) await rm(join(OUT_DIR, file));
}

for (const width of widths) {
  const info = await sharp(photo)
    .resize({ width })
    .webp({ quality: QUALITY, effort: 6, smartSubsample: true })
    .toFile(join(OUT_DIR, `hero-${width}.webp`));
  console.log(`[hero] hero-${width}.webp  ${info.width}x${info.height}  ${Math.round(info.size / 1024)} KB`);
}

// ~0.5 KB preview of the real photo, inlined in the HTML and shown blurred until the image paints.
const preview = await sharp(photo).resize({ width: PREVIEW_WIDTH }).webp({ quality: 55 }).toBuffer();

// Link previews (Open Graph): JPEG, which every crawler reads, at a size messaging apps accept.
const og = await sharp(photo)
  .resize({ width: Math.min(OG_WIDTH, sourceWidth) })
  .jpeg({ quality: 85, mozjpeg: true })
  .toFile(join(OUT_DIR, OG_FILE));
console.log(`[hero] ${OG_FILE}  ${og.width}x${og.height}  ${Math.round(og.size / 1024)} KB`);

const imports = widths.map((w) => `import hero${w} from './hero-${w}.webp';`).join('\n');
await writeFile(
  MODULE,
  `// Generated by scripts/generate-hero-images.mjs from public/images/hero.png. Do not edit.
// fingerprint: ${fingerprint}
${imports}
import heroOg from './${OG_FILE}';

/** Responsive variants, smallest first (static imports get hashed, long-cached URLs). */
export const heroVariants = [${widths.map((w) => `hero${w}`).join(', ')}];

/** Tiny inline preview shown (blurred) from the first paint until the photo arrives. */
export const heroPreview = 'data:image/webp;base64,${preview.toString('base64')}';

/** Link-preview (Open Graph) copy of the photo; its hashed URL changes whenever the photo does. */
export const heroOgImage = heroOg;

export const heroSourceSize = { width: ${sourceWidth}, height: ${sourceHeight} };
`,
);
console.log(`[hero] preview ${preview.length} bytes, wrote ${MODULE.replace(root + '/', '')}`);
